    private QueryTerms() {}

    static List<String> of(String query) {
        var terms = new LinkedHashSet<String>();
        var matcher = WORD.matcher(query.toLowerCase(Locale.ROOT));
        while (matcher.find() && terms.size() < MAXIMUM_TERMS) {
            var word = matcher.group();
            boolean digits = word.chars().allMatch(Character::isDigit);
            if ((digits ? word.length() >= 2 : word.length() >= 3) && !STOP_WORDS.contains(word))
                terms.add(word);
        }
        return List.copyOf(new ArrayList<>(terms));
    }
